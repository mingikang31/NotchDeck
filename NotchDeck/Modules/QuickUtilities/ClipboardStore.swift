import AppKit
import Foundation
import Observation

nonisolated struct ClipboardItem: Identifiable, Equatable, Sendable {
    enum Content: Equatable, Sendable {
        case text(String)
        /// PNG or TIFF data as it was on the clipboard.
        case image(Data, type: String)
        case files([URL])
    }

    var id = UUID()
    var content: Content
    var date = Date()
    /// The app that was frontmost when it was copied.
    var sourceApp: String?

    /// Same content, ignoring when and where it was copied (for de-duplication).
    func hasSameContent(as other: ClipboardItem) -> Bool { content == other.content }
}

/// Clipboard history: the last N text / image / file clips, kept in memory only (never written to
/// disk) and gone when NotchDeck quits.
///
/// macOS (15.4+) asks the user before an app reads what other apps copied. Watching `changeCount`
/// never asks, so the history only *reads* the clipboard automatically once NotchDeck is set to
/// **Allow** in System Settings → Privacy & Security → Paste from Other Apps. Until then each read
/// is an explicit click.
@Observable
final class ClipboardStore {
    enum Access: Equatable {
        /// Reads happen silently: history updates by itself.
        case allowed
        /// macOS would ask on every read (`.default` / `.ask`).
        case asks
        /// The user chose Deny in System Settings.
        case denied
    }

    /// Types password managers and system tools set to mark clips that shouldn't be recorded
    /// (nspasteboard.org conventions, plus 1Password's own).
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]
    static let maximumImageBytes = 12 * 1024 * 1024
    static let pollInterval: Duration = .milliseconds(500)

    private(set) var items: [ClipboardItem] = []
    private(set) var access: Access = .asks
    /// Something new was copied but couldn't be read without asking.
    private(set) var hasUnreadChange = false
    private(set) var lastCopiedID: ClipboardItem.ID?

    @ObservationIgnored private let settings: SettingsStore
    @ObservationIgnored private let pasteboard: NSPasteboard
    @ObservationIgnored private var lastChangeCount: Int
    @ObservationIgnored private var ownChangeCount: Int?
    @ObservationIgnored private var pollTask: Task<Void, Never>?
    @ObservationIgnored private var ticks = 0

    init(settings: SettingsStore, pasteboard: NSPasteboard = .general) {
        self.settings = settings
        self.pasteboard = pasteboard
        lastChangeCount = pasteboard.changeCount
    }

    func setActive(_ active: Bool) {
        if active {
            guard pollTask == nil else { return }
            refreshAccess()
            lastChangeCount = pasteboard.changeCount
            pollTask = Task { [weak self] in
                while !Task.isCancelled {
                    try? await Task.sleep(for: Self.pollInterval)
                    self?.poll()
                }
            }
        } else {
            pollTask?.cancel()
            pollTask = nil
            items.removeAll()
            hasUnreadChange = false
        }
    }

    // MARK: Actions

    /// Puts a clip back on the clipboard (ready to ⌘V) and moves it to the top.
    func copy(_ item: ClipboardItem) {
        pasteboard.clearContents()
        switch item.content {
        case .text(let text):
            pasteboard.setString(text, forType: .string)
        case .image(let data, let type):
            pasteboard.setData(data, forType: NSPasteboard.PasteboardType(type))
        case .files(let urls):
            pasteboard.writeObjects(urls as [NSURL])
        }
        ownChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
        items.removeAll { $0.id == item.id }
        var moved = item
        moved.date = Date()
        items.insert(moved, at: 0)
        lastCopiedID = moved.id
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
    }

    func clear() {
        items.removeAll()
    }

    /// Reads the clipboard once, on a click. While macOS is set to ask, this shows its prompt.
    func captureNow() {
        hasUnreadChange = false
        lastChangeCount = pasteboard.changeCount
        capture()
        refreshAccess()
    }

    /// Opens Privacy & Security so the user can set Paste from Other Apps to Allow.
    func openPrivacySettings() {
        if let url = URL(string: "x-apple.systempreferences:com.apple.settings.PrivacySecurity.extension") {
            NSWorkspace.shared.open(url)
        }
    }

    // MARK: Polling

    private func poll() {
        ticks += 1
        // The setting can change in System Settings at any time; re-check every few seconds.
        if ticks % 6 == 0 { refreshAccess() }
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if count == ownChangeCount { return }
        switch access {
        case .allowed:
            capture()
        case .asks, .denied:
            hasUnreadChange = true
        }
    }

    private func refreshAccess() {
        let new = Self.currentAccess(pasteboard)
        if new != access { access = new }
    }

    static func currentAccess(_ pasteboard: NSPasteboard) -> Access {
        guard #available(macOS 15.4, *) else { return .allowed }
        return switch pasteboard.accessBehavior {
        case .alwaysAllow: .allowed
        case .alwaysDeny: .denied
        default: .asks
        }
    }

    private func capture() {
        guard let item = Self.read(pasteboard, includeImages: settings.clipboardCapturesImages) else { return }
        var new = item
        new.sourceApp = NSWorkspace.shared.frontmostApplication?.localizedName
        items = Self.inserting(new, into: items, limit: settings.clipboardHistoryLimit)
    }

    /// Adds a clip at the top, dropping an older identical one and anything past the limit.
    nonisolated static func inserting(_ item: ClipboardItem, into items: [ClipboardItem], limit: Int) -> [ClipboardItem] {
        var result = items.filter { !$0.hasSameContent(as: item) }
        result.insert(item, at: 0)
        return Array(result.prefix(max(1, limit)))
    }

    /// Text, an image or file references, unless the clip is marked concealed / transient.
    static func read(_ pasteboard: NSPasteboard, includeImages: Bool) -> ClipboardItem? {
        let types = pasteboard.types ?? []
        guard !types.contains(where: { ignoredTypes.contains($0.rawValue) }) else { return nil }

        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return ClipboardItem(content: .files(urls))
        }
        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return ClipboardItem(content: .text(text))
        }
        if includeImages {
            for type in [NSPasteboard.PasteboardType.png, .tiff] where types.contains(type) {
                if let data = pasteboard.data(forType: type), data.count <= maximumImageBytes {
                    return ClipboardItem(content: .image(data, type: type.rawValue))
                }
            }
        }
        return nil
    }
}
